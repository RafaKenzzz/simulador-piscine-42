/*
** O atoi da biblioteca: espaços (isspace), UM sinal opcional, algarismos.
** Ao contrário do ft_atoi do C04, "--5" dá 0.
*/
int	ft_atoi(const char *str)
{
	int	sign;
	int	result;

	while (*str == ' ' || (*str >= 9 && *str <= 13))
		str++;
	sign = 1;
	if (*str == '-' || *str == '+')
	{
		if (*str == '-')
			sign = -1;
		str++;
	}
	result = 0;
	while (*str >= '0' && *str <= '9')
	{
		result = result * 10 + (*str - '0');
		str++;
	}
	return (result * sign);
}
